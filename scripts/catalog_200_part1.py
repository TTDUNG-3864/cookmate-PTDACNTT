def apply_verified_catalog_images(recipes: list[dict[str, Any]]) -> None:
    import json
    from pathlib import Path

    manifest = Path(__file__).resolve().parent / "verified_images_200.json"
    if not manifest.exists():
        return
    try:
        data = json.loads(manifest.read_text(encoding="utf-8"))
        by_title = data.get("recipes_by_title") or {}
        for item in recipes:
            url = by_title.get(item.get("title", ""))
            if url:
                item["image"] = url
    except Exception:
        pass


